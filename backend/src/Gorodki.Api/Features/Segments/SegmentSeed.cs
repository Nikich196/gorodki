    /// <summary>Строки таблицы <c>segments</c>: линия в UTM 34N на сетке 0,1 м и её длина.</summary>
    public static IEnumerable<SegmentEntity> Entities() => Entries.Select(e =>
    {
        var line = Line(e.LatLon);
        return new SegmentEntity
        {
            Id = e.Id,
            Name = e.Name,
            League = e.League,
            Line = line,
            LengthMeters = Math.Round(line.Length, 1),
            Proposal = true,
        };
    });

    /// <summary>Линия из «широта, долгота, …» — в UTM 34N, на сетке 0,1 м.</summary>
    public static LineString Line(IReadOnlyList<double> latLon)
    {
        var coordinates = new Coordinate[latLon.Count / 2];
        for (var i = 0; i < coordinates.Length; i++)
        {
            var (x, y) = Utm34.Forward(latLon[2 * i], latLon[(2 * i) + 1]);
            coordinates[i] = GeoOps.Snap(new Coordinate(x, y));
        }

        return GeoOps.Factory.CreateLineString(coordinates);
    }

    /// <summary>Линия для засчитывания проходов (<see cref="SegmentEffortDetector"/>).</summary>
    public static SegmentCourse Course(LineString line) => new(line.Coordinates);
