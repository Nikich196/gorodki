namespace Gorodki.Domain.Territory;

/// <summary>
/// Мягкий сброс земли при смене сезона (PLAN.md, §3.4; решено 25.09 в #30, п. 1–2) — чистая функция состояния куска.
/// </summary>
/// <remarks>
/// <list type="bullet">
/// <item>уровень → 1;</item>
/// <item>«последний визит» сдвигается так, чтобы куску осталось меньшее из двух: срок угасания одного уровня (6 дней) или
/// сколько оставалось до исчезновения. Живая земля в момент сброса не исчезает, давно брошенная уходит раньше; уже
/// угасшая («призрак») исчезает тогда же, когда исчезла бы без сброса;</item>
/// <item>щиты снимаются, а с ними осада и окно снятия уровней;</item>
/// <item>владелец, контур, время последнего повышения и касание владельца (<see cref="ParcelState.TouchedAt"/>) не меняются:
/// «касались в этом сезоне» — это касание не раньше начала нового сезона, и сброс его не даёт.</item>
/// </list>
/// Сервер применяет ту же формулу одним SQL-запросом ко всей земле лиги и к журналу захватов (<c>SeasonRollover</c>);
/// интеграционный тест сверяет запрос с этой функцией.
/// </remarks>
public static class SeasonReset
{
    /// <summary>Состояние куска после мягкого сброса в момент <paramref name="seasonStart"/> (начало нового сезона).</summary>
    /// <remarks>
    /// До исчезновения оставалось <c>LastVisitAt + уровень × D − T</c> (<see cref="Decay.LostAt"/>); после сброса уровень 1,
    /// и остаётся <c>LastVisitAt' + D − T</c>. Приравняв это к меньшему из <c>D</c> и прежнего остатка, получаем
    /// <c>LastVisitAt' = min(T, LastVisitAt + (уровень − 1) × D)</c>. Визит уже после начала сезона (задача сброса
    /// опоздала) назад не сдвигается: берётся большее из этого и прежнего визита. Повторный сброс с тем же
    /// <paramref name="seasonStart"/> ничего не меняет.
    /// </remarks>
    public static ParcelState Soft(ParcelState state, DateTimeOffset seasonStart, TerritoryRules rules)
    {
        var shifted = state.LastVisitAt + (rules.DecayInterval * (state.Level - 1));
        var lastVisit = Max(state.LastVisitAt, Min(seasonStart, shifted));
        return state with
        {
            Level = 1,
            LastVisitAt = lastVisit,
            ShieldUntil = null,
            SiegeUntil = null,
            LossWindowSince = null,
            LossAttackers = AttackerSet.Empty,
        };
    }

    /// <summary>
    /// Петля или визит со временем раньше начала сезона, применённые, когда смена на этот сезон уже прошла: кусок, который
    /// событие изменило, проходит тот же мягкий сброс — будто событие пришло до смены (§3.4: «петля относится к сезону по
    /// времени замыкания, а не обработки»). Так бывает каждую смену: визиты забега, кончившегося после ~23:35, считаются
    /// после границы публичности, уже после полуночи; петля последних минут или из офлайна применяется до 3 ч спустя.
    /// </summary>
    /// <param name="before">Кусок до события — уже сброшенный.</param>
    /// <param name="after">Кусок после события (<see cref="CaptureRules.Decide"/>, <see cref="CaptureRules.Visit"/>).</param>
    /// <param name="at">Время события.</param>
    /// <param name="seasonStart">
    /// Начало идущего сезона, если смена на него уже прошла; <c>null</c> — смена ещё впереди (она сама сбросит итог события)
    /// или сезоны не начались.
    /// </param>
    /// <remarks>
    /// <para>
    /// Без этого визит в 23:50 поднимал бы уровень уже сброшенной земли: визит видит L1 и давнее повышение уровня, а в порядке
    /// «визит, потом сброс» тот же подъём снял бы сброс. L2 с «последним визитом» у полуночи живёт 12 дней вместо 6 и первые
    /// 6 дней одной петлёй не переходит. Взятая петлёй в 23:50 земля уносила бы в новый сезон щит.
    /// </para>
    /// <para>
    /// Кусок, который событие не изменило, остаётся как есть: в нём может быть то, что появилось уже в новом сезоне (уровень,
    /// поднятый после полуночи, щит, осада), — второй сброс стёр бы это. Событие до полуночи такой кусок и не меняет:
    /// «последний визит» и касание у него уже позже события, а время повышения уровня не даёт поднять уровень.
    /// </para>
    /// <para>
    /// Не вернуть только то, что сброс уже стёр: щит, осаду и окно снятия уровней «до». Поэтому опоздавшая чужая петля по
    /// куску, который до полуночи был под щитом, его возьмёт (после полуночи его может взять любой), а L2–L3 не треснет
    /// (<see cref="PieceOutcome.Superseded"/>: сброс сдвинул «последний визит» на полночь; земля та же, что после трещины и
    /// сброса, — нападающий теряет только очки трещины). У визита, чей подъём уровня снят, время повышения — время визита:
    /// так и в порядке «визит, потом сброс», если подъём был; если его не было (L3 или осада «до»), следующий подъём
    /// возможен до 20 ч позже — опоздание преимуществ не даёт.
    /// </para>
    /// </remarks>
    public static ParcelState? Late(
        ParcelState? before, ParcelState? after, DateTimeOffset at, DateTimeOffset? seasonStart, TerritoryRules rules) =>
        seasonStart is { } start && at < start && after is not null && after != before ? Soft(after, start, rules) : after;

    private static DateTimeOffset Max(DateTimeOffset a, DateTimeOffset b) => a > b ? a : b;

    private static DateTimeOffset Min(DateTimeOffset a, DateTimeOffset b) => a < b ? a : b;
}
